"""Plane groups: box rig from the nearest and farthest plane, click selects the
group, double click enters it and fades the planes outside.

Run with Blender 5.2 or 5.3:
    blender -b --factory-startup --python-exit-code 1 \
        --python frame_by_plane/tests/plane_groups_regression.py
"""

import importlib
import math
import os
import sys
import tempfile
import traceback
from pathlib import Path

import bpy


INSTALLED_PACKAGE = os.environ.get("FBP_TEST_INSTALLED") == "1"
PACKAGE_NAME = os.environ.get(
    "FBP_TEST_PACKAGE",
    "bl_ext.fbp_audit.frame_by_plane" if INSTALLED_PACKAGE else "frame_by_plane",
)
if not INSTALLED_PACKAGE:
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
addon = importlib.import_module(PACKAGE_NAME)
if not INSTALLED_PACKAGE:
    addon.register()


def rigs():
    return [obj for obj in bpy.context.scene.objects if bool(getattr(obj, "is_fbp_control", False))]


def material_opacity(rig):
    values = []
    for mat in rig.fbp_plane_target.data.materials:
        if mat is not None:
            values.append(round(float(mat.get("fbp_opacity", 1.0)), 4))
    return values


try:
    groups = importlib.import_module(f"{PACKAGE_NAME}.plane_groups")
    operator_import = importlib.import_module(f"{PACKAGE_NAME}.operator_import")
    operator_layers = importlib.import_module(f"{PACKAGE_NAME}.operator_layers")
    for operator_class in (
        operator_import.FBP_OT_ImportSequence,
        operator_import.FBP_OT_GenerateMultiplane,
        operator_layers.FBP_OT_CreateLayerCollection,
    ):
        if getattr(bpy.types, operator_class.__name__, None) is None:
            bpy.utils.register_class(operator_class)

    workdir = Path(tempfile.mkdtemp(prefix="fbp_plane_groups_"))
    names = []
    for index, size in enumerate(((16, 9), (8, 8), (12, 20), (10, 10)), start=1):
        image = bpy.data.images.new(f"FBP Group {index}", width=size[0], height=size[1], alpha=True)
        try:
            image.generated_color = (0.2 * index, 0.4, 0.6, 1.0)
            image.filepath_raw = str(workdir / f"layer_{index}.png")
            image.file_format = 'PNG'
            image.save()
        finally:
            bpy.data.images.remove(image)
        names.append(f"layer_{index}.png")

    for obj in list(bpy.data.objects):
        bpy.data.objects.remove(obj, do_unlink=True)
    scene = bpy.context.scene
    camera_data = bpy.data.cameras.new("Group Camera")
    camera = bpy.data.objects.new("Group Camera", camera_data)
    camera.location = (0.0, -12.0, 0.0)
    camera.rotation_euler = (math.radians(90.0), 0.0, 0.0)
    scene.collection.objects.link(camera)
    scene.camera = camera
    bpy.context.view_layer.update()

    rows = [(f"L{index}", "", str(workdir), [name], False) for index, name in enumerate(names)]
    assert operator_import._fbp_prepare_pending_rows(bpy.context, str(workdir), rows) == 4
    result = bpy.ops.fbp.generate_multiplane('EXEC_DEFAULT', camera_mode='KEEP')
    assert 'FINISHED' in result, result
    layers = sorted(rigs(), key=lambda obj: obj.fbp_depth_order)
    assert len(layers) == 4, [obj.name for obj in layers]

    # Collections generated by the import are never plane groups.
    import_collections = {coll for rig in layers for coll in rig.users_collection}
    assert not any(groups.is_plane_group(coll) for coll in import_collections), import_collections

    # 1. Ctrl+G on three layers makes a plane group.
    bpy.ops.object.select_all(action='DESELECT')
    for rig in layers[:3]:
        rig.select_set(True)
    bpy.context.view_layer.objects.active = layers[0]
    assert bpy.ops.fbp.create_layer_collection('EXEC_DEFAULT', mode='PLANES') == {'FINISHED'}
    group = groups.group_chain(layers[0], scene)[-1]
    assert groups.is_plane_group(group), group
    members = groups.group_rigs(group, scene)
    assert set(members) == set(layers[:3]), members
    outside = layers[3]
    assert groups.group_chain(outside, scene) == []

    # 2. The box joins the nearest and the farthest plane at their corners.
    bpy.context.view_layer.update()
    depsgraph = bpy.context.evaluated_depsgraph_get()
    front, back = groups.group_box(group, bpy.context, depsgraph)
    depth_of = lambda points: sum((p - camera.location).dot((0.0, 1.0, 0.0)) for p in points) / 4.0
    member_depths = sorted(
        (rig.matrix_world.translation - camera.location).dot((0.0, 1.0, 0.0)) for rig in members
    )
    assert abs(depth_of(front) - member_depths[0]) < 1e-3, (depth_of(front), member_depths)
    assert abs(depth_of(back) - member_depths[-1]) < 1e-3, (depth_of(back), member_depths)
    segments = groups.box_segments(front, back)
    assert len(segments) == 24, len(segments)
    # The middle plane adds no outline.
    middle = [rig for rig in members if abs(
        (rig.matrix_world.translation - camera.location).dot((0.0, 1.0, 0.0)) - member_depths[1]
    ) < 1e-6][0]
    middle_corners = groups._rect_corners(middle, depsgraph)
    assert not any((corner - point).length < 1e-6 for corner in middle_corners for point in segments)

    # 3. A click on a member selects the whole group.
    assert groups.selection_group(layers[1], scene) == group
    assert groups.rig_in_closed_group(layers[1], scene)
    bpy.ops.object.select_all(action='DESELECT')
    assert groups.select_group(bpy.context, group, layers[1])
    assert all(rig.select_get() for rig in members)
    assert not outside.select_get()
    assert bpy.context.view_layer.objects.active == layers[1].fbp_plane_target
    assert groups.whole_group_selected_rigs(bpy.context) == {rig.name for rig in members}
    # Toggle (Shift) deselects a fully selected group.
    assert groups.select_group(bpy.context, group, layers[1], toggle=True)
    assert not any(rig.select_get() for rig in members)

    # 4. Entering the group: single planes, the outside planes fade.
    groups.enter_group(scene, group)
    assert groups.entered_group(scene) == group
    assert groups.selection_group(layers[1], scene) is None
    assert not groups.rig_in_closed_group(layers[1], scene)
    assert groups.rig_outside_entered_group(outside, scene)
    assert material_opacity(outside) == [groups.ISOLATION_FADE], material_opacity(outside)
    assert all(material_opacity(rig) == [1.0] for rig in members), [material_opacity(r) for r in members]
    assert abs(float(outside.fbp_opacity) - 1.0) < 1e-6, "the layer's own Opacity never changes"
    # Solid > Material: the faded planes are darkened too, the group's are not.
    outside_mat = outside.fbp_plane_target.data.materials[0]
    original_rgb = tuple(groups._SOLID_COLORS[outside_mat.name])
    assert all(
        abs(a - b * groups.ISOLATION_SOLID_DIM) < 1e-5
        for a, b in zip(tuple(outside_mat.diffuse_color)[:3], original_rgb)
    ), (tuple(outside_mat.diffuse_color), original_rgb)
    assert all(mat.name not in groups._SOLID_COLORS for rig in members for mat in rig.fbp_plane_target.data.materials)

    # 5. Save never stores the fade; it comes back afterwards.
    path = workdir / "groups.blend"
    groups.fbp_plane_group_suspend()
    assert material_opacity(outside) == [1.0], material_opacity(outside)
    groups.fbp_plane_group_resume()
    groups._reapply_everything()
    assert material_opacity(outside) == [groups.ISOLATION_FADE], material_opacity(outside)
    bpy.ops.wm.save_as_mainfile(filepath=str(path), copy=True)
    assert material_opacity(outside) == [1.0], "save_pre restores"
    groups._reapply_everything()
    assert material_opacity(outside) == [groups.ISOLATION_FADE]

    # 6. Exit restores every plane.
    groups.exit_group(scene)
    assert groups.entered_group(scene) is None
    assert material_opacity(outside) == [1.0], material_opacity(outside)
    assert groups.selection_group(layers[1], scene) == group
    assert all(abs(a - b) < 1e-6 for a, b in zip(tuple(outside_mat.diffuse_color)[:3], original_rgb))
    assert not groups._SOLID_COLORS

    # 7. Nested groups open one level at a time.
    bpy.ops.object.select_all(action='DESELECT')
    for rig in layers[:2]:
        rig.select_set(True)
    bpy.context.view_layer.objects.active = layers[0]
    assert bpy.ops.fbp.create_layer_collection('EXEC_DEFAULT', mode='PLANES') == {'FINISHED'}
    chain = groups.group_chain(layers[0], scene)
    assert len(chain) == 2 and chain[0] == group, chain
    inner = chain[1]
    assert groups.selection_group(layers[0], scene) == group
    groups.enter_group(scene, group)
    assert groups.selection_group(layers[0], scene) == inner
    assert groups.selection_group(layers[2], scene) is None
    groups.enter_group(scene, inner)
    assert material_opacity(layers[2]) == [groups.ISOLATION_FADE]
    groups.exit_group(scene, to_parent=True)
    assert groups.entered_group(scene) == group
    assert material_opacity(layers[2]) == [1.0]
    groups.exit_group(scene)

    # 8. The Group Rig switch turns a collection off.
    group.fbp_plane_group = False
    assert groups.selection_group(layers[2], scene) is None
    assert groups.group_box(group, bpy.context, depsgraph) is not None  # geometry still computable
    assert group not in groups._scene_groups(scene)

    # 9. The saved copy reopens with full opacity everywhere.
    bpy.ops.wm.open_mainfile(filepath=str(path))
    for rig in rigs():
        assert material_opacity(rig) == [1.0], (rig.name, material_opacity(rig))
    assert groups.entered_group(bpy.context.scene) is None

    print("FBPTEST plane groups: PASS")
except Exception:
    traceback.print_exc()
    sys.exit(1)
