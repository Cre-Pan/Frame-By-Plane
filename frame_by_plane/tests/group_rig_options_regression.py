"""Plane group rig options: show or hide, Digital or Legacy, Box or Fit to
Planes, and the Rig Shape button opening them for a selected group.

Run with Blender 5.2 or 5.3:
    blender -b --factory-startup --python-exit-code 1 \
        --python frame_by_plane/tests/group_rig_options_regression.py
"""

import importlib
import math
import os
import sys
import tempfile
import traceback
from pathlib import Path

import bpy


INSTALLED_PACKAGE = os.environ.get("FBP_TEST_INSTALLED") == "1"
PACKAGE_NAME = os.environ.get(
    "FBP_TEST_PACKAGE",
    "bl_ext.fbp_audit.frame_by_plane" if INSTALLED_PACKAGE else "frame_by_plane",
)
if not INSTALLED_PACKAGE:
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
addon = importlib.import_module(PACKAGE_NAME)
if not INSTALLED_PACKAGE:
    addon.register()


def rigs():
    return [obj for obj in bpy.context.scene.objects if bool(getattr(obj, "is_fbp_control", False))]


def material_opacity(rig):
    values = []
    for mat in rig.fbp_plane_target.data.materials:
        if mat is not None:
            values.append(round(float(mat.get("fbp_opacity", 1.0)), 4))
    return values


try:
    groups = importlib.import_module(f"{PACKAGE_NAME}.plane_groups")
    operator_import = importlib.import_module(f"{PACKAGE_NAME}.operator_import")
    operator_layers = importlib.import_module(f"{PACKAGE_NAME}.operator_layers")
    for operator_class in (
        operator_import.FBP_OT_ImportSequence,
        operator_import.FBP_OT_GenerateMultiplane,
        operator_layers.FBP_OT_CreateLayerCollection,
    ):
        if getattr(bpy.types, operator_class.__name__, None) is None:
            bpy.utils.register_class(operator_class)

    workdir = Path(tempfile.mkdtemp(prefix="fbp_group_rig_"))
    names = []
    for index, size in enumerate(((16, 9), (8, 8), (12, 20), (10, 10)), start=1):
        image = bpy.data.images.new(f"FBP Group {index}", width=size[0], height=size[1], alpha=True)
        try:
            image.generated_color = (0.2 * index, 0.4, 0.6, 1.0)
            image.filepath_raw = str(workdir / f"layer_{index}.png")
            image.file_format = 'PNG'
            image.save()
        finally:
            bpy.data.images.remove(image)
        names.append(f"layer_{index}.png")

    for obj in list(bpy.data.objects):
        bpy.data.objects.remove(obj, do_unlink=True)
    scene = bpy.context.scene
    camera_data = bpy.data.cameras.new("Group Camera")
    camera = bpy.data.objects.new("Group Camera", camera_data)
    camera.location = (0.0, -12.0, 0.0)
    camera.rotation_euler = (math.radians(90.0), 0.0, 0.0)
    scene.collection.objects.link(camera)
    scene.camera = camera
    bpy.context.view_layer.update()

    rows = [(f"L{index}", "", str(workdir), [name], False) for index, name in enumerate(names)]
    assert operator_import._fbp_prepare_pending_rows(bpy.context, str(workdir), rows) == 4
    result = bpy.ops.fbp.generate_multiplane('EXEC_DEFAULT', camera_mode='KEEP')
    assert 'FINISHED' in result, result
    layers = sorted(rigs(), key=lambda obj: obj.fbp_depth_order)
    assert len(layers) == 4, [obj.name for obj in layers]

    # Collections generated by the import are never plane groups.
    import_collections = {coll for rig in layers for coll in rig.users_collection}
    assert not any(groups.is_plane_group(coll) for coll in import_collections), import_collections

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from ui_layout_stub import StubLayout, StubPanel
    ui = importlib.import_module(f"{PACKAGE_NAME}.ui")
    controller_module = importlib.import_module(f"{PACKAGE_NAME}.group_controller")
    for operator_class in controller_module._CLASSES:
        if getattr(bpy.types, operator_class.__name__, None) is None:
            bpy.utils.register_class(operator_class)

    # Ctrl+G on three layers.
    bpy.ops.object.select_all(action='DESELECT')
    for rig in layers[:3]:
        rig.select_set(True)
    bpy.context.view_layer.objects.active = layers[0]
    assert bpy.ops.fbp.create_layer_collection('EXEC_DEFAULT', mode='PLANES') == {'FINISHED'}
    group = groups.group_chain(layers[0], scene)[-1]
    members = groups.group_rigs(group, scene)
    bpy.context.view_layer.update()
    depsgraph = bpy.context.evaluated_depsgraph_get()

    def shown():
        return {coll for coll, _segments in groups.visible_group_boxes(bpy.context, depsgraph)}

    def segments_of(coll):
        return dict(groups.visible_group_boxes(bpy.context, depsgraph)).get(coll)

    # 1. Defaults keep the earlier look: shown, Legacy (always), Box.
    assert group.fbp_group_rig_visible is True
    assert group.fbp_group_rig_style == 'LEGACY'
    assert group.fbp_group_rig_shape == 'BOX'
    bpy.ops.object.select_all(action='DESELECT')
    assert group in shown()
    assert len(segments_of(group)) == 24

    # 2. Fit to Planes: every plane's outline, joined one to the next.
    group.fbp_group_rig_shape = 'FIT'
    segments = segments_of(group)
    count = len(members)
    assert len(segments) == 2 * (4 * count + 4 * (count - 1)), len(segments)
    for rig in members:
        corners = groups._rect_corners(rig, depsgraph)
        assert all(any((corner - point).length < 1e-6 for point in segments) for corner in corners), rig.name
    group.fbp_group_rig_shape = 'BOX'

    # 3. Digital: shown only while the group is selected (or partly) or entered.
    group.fbp_group_rig_style = 'DIGITAL'
    assert group not in shown()
    layers[3].select_set(True)
    assert group not in shown()
    bpy.ops.object.select_all(action='DESELECT')
    members[0].select_set(True)
    assert group in shown()
    bpy.ops.object.select_all(action='DESELECT')
    groups.enter_group(scene, group)
    assert group in shown()
    groups.exit_group(scene)
    assert groups.select_group(bpy.context, group, members[0])
    assert group in shown()

    # 4. Hidden: never drawn, never clicked, whatever the style.
    group.fbp_group_rig_visible = False
    assert group not in shown()
    group.fbp_group_rig_style = 'LEGACY'
    assert group not in shown()
    group.fbp_group_rig_visible = True
    assert group in shown()

    # 5. The Rig Shape button: group options when the whole group is selected.
    assert groups.select_group(bpy.context, group, members[0])
    assert ui._fbp_whole_group_selected(bpy.context) == group
    stub = StubLayout()
    ui._fbp_draw_group_rig_options(stub, group, members[0].name)
    props = [args[1] for name, args, _kw in stub.calls if name == "prop"]
    assert props == ["fbp_group_rig_visible", "fbp_group_rig_style", "fbp_group_rig_shape", "color_tag"], props
    panel = StubPanel()
    ui.FBP_PT_Sequence.draw(panel, bpy.context)
    texts = [kw.get("text") for name, _args, kw in panel.layout.calls if name == "operator"]
    assert "Group Rig" in texts, texts
    # A single layer still gets its own Rig Shape.
    bpy.ops.object.select_all(action='DESELECT')
    layers[3].select_set(True)
    bpy.context.view_layer.objects.active = layers[3]
    assert ui._fbp_whole_group_selected(bpy.context) is None
    panel = StubPanel()
    ui.FBP_PT_Sequence.draw(panel, bpy.context)
    texts = [kw.get("text") for name, _args, kw in panel.layout.calls if name == "operator"]
    assert "Rig Shape" in texts and "Group Rig" not in texts, texts

    # 6. With a controller, the selected controller shows the group block.
    bpy.ops.object.select_all(action='DESELECT')
    bpy.context.view_layer.objects.active = members[0]
    members[0].select_set(True)
    assert bpy.ops.fbp.add_group_controller('EXEC_DEFAULT', group_name=group.name) == {'FINISHED'}
    controller = controller_module.group_controller(group)
    assert bpy.context.view_layer.objects.active == controller and controller.select_get()
    assert ui._fbp_whole_group_selected(bpy.context) == group
    panel = StubPanel()
    ui.FBP_PT_Sequence.draw(panel, bpy.context)
    texts = [kw.get("text") for name, _args, kw in panel.layout.calls if name == "operator"]
    assert "Group Rig" in texts, texts
    group.fbp_group_rig_style = 'DIGITAL'
    assert group in shown()
    controller.select_set(False)
    assert group not in shown()

    # 7. The options are saved with the file.
    group.fbp_group_rig_shape = 'FIT'
    group.fbp_group_rig_visible = False
    path = workdir / "group_rig.blend"
    bpy.ops.wm.save_as_mainfile(filepath=str(path))
    bpy.ops.wm.open_mainfile(filepath=str(path))
    reopened = next(coll for coll in bpy.data.collections if groups.is_plane_group(coll))
    assert reopened.fbp_group_rig_shape == 'FIT'
    assert reopened.fbp_group_rig_style == 'DIGITAL'
    assert reopened.fbp_group_rig_visible is False

    print("FBPTEST group rig options: PASS")
except Exception:
    traceback.print_exc()
    sys.exit(1)
