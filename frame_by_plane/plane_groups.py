def _rig_under_cursor(context, event):
    try:
        from .alpha_pick import fbp_layer_under_cursor
        return fbp_layer_under_cursor(context, (event.mouse_region_x, event.mouse_region_y))
    except (ImportError, *FBP_DATA_ERRORS, ValueError):
        return None


def _view3d_object_mode(context):
    return (
        getattr(context, "mode", "") == 'OBJECT'
        and getattr(getattr(context, "area", None), "type", "") == 'VIEW_3D'
        and getattr(context, "region_data", None) is not None
    )


class FBP_OT_EnterPlaneGroup(Operator):
    """Enter the group under the cursor and select the plane that was clicked"""

    bl_idname = "fbp.enter_plane_group"
    bl_label = "Enter Group"
    bl_description = (
        "Double-click a plane of a group to work inside the group: the plane is "
        "selected and planes outside the group are faded"
    )
    bl_options = {'REGISTER'}

    group: StringProperty(name="Group", default="", options={'SKIP_SAVE', 'HIDDEN'})

    @classmethod
    def poll(cls, context):
        return getattr(context, "scene", None) is not None

    def invoke(self, context, event):
        if not _view3d_object_mode(context):
            return {'PASS_THROUGH'}
        scene = context.scene
        rig = _rig_under_cursor(context, event)
        if rig is None:
            if entered_group(scene) is not None:
                exit_group(scene)
                return {'FINISHED'}
            return {'PASS_THROUGH'}
        if rig_outside_entered_group(rig, scene):
            exit_group(scene)
        target = selection_group(rig, scene)
        if target is None:
            if entered_group(scene) is None:
                # Not in a group: Blender's own double click.
                return {'PASS_THROUGH'}
        else:
            enter_group(scene, target)
        self._select_single(context, rig)
        return {'FINISHED'}

    def execute(self, context):
        scene = context.scene
        collection = bpy.data.collections.get(self.group)
        if collection is None or not is_plane_group(collection):
            return {'CANCELLED'}
        enter_group(scene, collection)
        return {'FINISHED'}

    @staticmethod
    def _select_single(context, rig):
        for obj in tuple(getattr(context, "selected_objects", ()) or ()):
            if obj != rig:
                try:
                    obj.select_set(False)
                except FBP_DATA_ERRORS:
                    pass
        try:
            rig.select_set(True)
            plane = getattr(rig, "fbp_plane_target", None)
            if plane is not None and plane.name not in context.view_layer.objects:
                plane = None
            context.view_layer.objects.active = plane or rig
        except FBP_DATA_ERRORS:
            pass


class FBP_OT_ExitPlaneGroup(Operator):
    """Leave the entered group: every plane is shown at full opacity again"""

    bl_idname = "fbp.exit_plane_group"
    bl_label = "Exit Group"
    bl_description = "Leave the entered group; planes outside it are shown at full opacity again"
    bl_options = {'REGISTER'}

    to_parent: BoolProperty(
        name="To Parent Group",
        description="Go up one level when the group is inside another group",
        default=True,
        options={'SKIP_SAVE'},
    )

    @classmethod
    def poll(cls, context):
        return entered_group(getattr(context, "scene", None)) is not None

    def execute(self, context):
        scene = context.scene
        entered = entered_group(scene)
        exit_group(scene, to_parent=bool(self.to_parent))
        if entered is not None:
            select_group(context, entered)
        return {'FINISHED'}


_CLASSES = (FBP_OT_EnterPlaneGroup, FBP_OT_ExitPlaneGroup)


def register():
    global _DRAW_HANDLE, _BADGE_HANDLE
    bpy.types.Collection.fbp_plane_group = BoolProperty(
        name="Group Rig",
        description=(
            "Treat this collection as a plane group: draw its box rig (nearest and "
            "farthest plane joined at the corners), select it with one click and "
            "enter it with a double click"
        ),
        default=False,
        update=lambda _self, _context: _tag_viewports(),
    )
    register_interactive_classes(_CLASSES)
    for name, callback in _HANDLERS:
        append_handler_once(getattr(bpy.app.handlers, name), callback, module_suffix="plane_groups")
    if not bpy.app.background:
        if _DRAW_HANDLE is None:
            _DRAW_HANDLE = bpy.types.SpaceView3D.draw_handler_add(
                _draw_group_boxes, (), "WINDOW", "POST_VIEW"
            )
        if _BADGE_HANDLE is None:
            _BADGE_HANDLE = bpy.types.SpaceView3D.draw_handler_add(
                _draw_isolation_badge, (), "WINDOW", "POST_PIXEL"
            )


def unregister():
    global _DRAW_HANDLE, _BADGE_HANDLE
    try:
        _restore_everything()
    except FBP_DATA_ERRORS:
        pass
    _ENTERED.clear()
    _FADED.clear()
    _SOLID_COLORS.clear()
    for handle in (_DRAW_HANDLE, _BADGE_HANDLE):
        if handle is not None:
            try:
                bpy.types.SpaceView3D.draw_handler_remove(handle, "WINDOW")
            except (ValueError, RuntimeError):
                pass
    _DRAW_HANDLE = None
    _BADGE_HANDLE = None
    for name, callback in _HANDLERS:
        remove_handlers_by_name(getattr(bpy.app.handlers, name), callback.__name__, module_suffix="plane_groups")
    try:
        if bpy.app.timers.is_registered(_reapply_everything):
            bpy.app.timers.unregister(_reapply_everything)
    except FBP_DATA_ERRORS:
        pass
    unregister_classes(_CLASSES)
    try:
        del bpy.types.Collection.fbp_plane_group
    except AttributeError:
        pass
