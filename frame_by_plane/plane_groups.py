"""Plane groups: a box rig around each group and Grease Pencil style isolation.

A plane group is a Frame By Plane collection created by the artist (Ctrl+G or
the Layer List), never one generated by an import. It is marked with
``Collection.fbp_plane_group``.

* The group's rig is drawn in the viewport as a box: the outline of the
  nearest plane, the outline of the farthest plane, and four lines joining
  their corners. Planes in between add nothing, so the box shows where the
  group starts and ends in depth whatever the size of each plane.
* A click on a plane of a group selects the whole group. A double click
  enters the group and selects that plane: while inside, a click selects
  single planes and every plane outside the group is shown at a reduced
  opacity, as in Grease Pencil Edit Mode. Esc, a double click on empty space
  or a click on a plane outside the group leaves it.

The reduced opacity is a view state only: it is never saved in the file,
never rendered and it is undone before Save and before a render starts.
"""

from __future__ import annotations

import bpy
from bpy.props import BoolProperty, StringProperty
from bpy.types import Operator
from mathutils import Vector

from .runtime import FBP_DATA_ERRORS
from .registration import (
    append_handler_once,
    register_interactive_classes,
    remove_handlers_by_name,
    unregister_classes,
)


# Opacity of the planes outside the entered group, as a factor of their own.
ISOLATION_FADE = 0.25
# Solid > Material: their viewport colour is darkened by this factor too.
ISOLATION_SOLID_DIM = 0.35

_GROUP_LINE_WIDTH = 1.0
_GROUP_SELECTED_WIDTH = 2.0
_GROUP_HALO_EXTRA = 2.0
_DEFAULT_GROUP_COLOR = (0.82, 0.82, 0.82)

_DRAW_HANDLE = None
_BADGE_HANDLE = None
_LINE_SHADER = None

# Scene pointer -> name of the entered group collection.
_ENTERED = {}
# Scene pointer -> names of the rigs currently faded by the isolation.
_FADED = {}
# Material name -> viewport colour (RGB) before the fade darkened it.
_SOLID_COLORS = {}
# Rigs restored before Save or a render, faded again right after.
_SUSPENDED = {"active": False}


# -- Groups -----------------------------------------------------------------

def is_plane_group(collection) -> bool:
    """True for a collection the artist made into a plane group."""
    if collection is None:
        return False
    try:
        return bool(getattr(collection, "fbp_plane_group", False))
    except FBP_DATA_ERRORS:
        return False


def _any_groups() -> bool:
    """Cheap early-out: no plane group exists in the file."""
    try:
        return any(is_plane_group(collection) for collection in bpy.data.collections)
    except FBP_DATA_ERRORS:
        return False


def _scene_key(scene) -> int:
    try:
        return int(scene.as_pointer()) if scene is not None else 0
    except FBP_DATA_ERRORS:
        return 0


def _parent_map(scene):
    """``{collection pointer: parent collection}`` for the scene tree."""
    result = {}
    root = getattr(scene, "collection", None)
    if root is None:
        return result
    stack = [root]
    seen = set()
    while stack:
        parent = stack.pop()
        try:
            key = int(parent.as_pointer())
        except FBP_DATA_ERRORS:
            continue
        if key in seen:
            continue
        seen.add(key)
        try:
            children = tuple(parent.children)
        except FBP_DATA_ERRORS:
            continue
        for child in children:
            try:
                result.setdefault(int(child.as_pointer()), parent)
            except FBP_DATA_ERRORS:
                continue
            stack.append(child)
    return result


def _layer_collection(rig):
    try:
        from .layers import get_primary_fbp_collection
        return get_primary_fbp_collection(rig)
    except (ImportError, *FBP_DATA_ERRORS):
        return None


def group_chain(rig, scene, parent_map=None):
    """Plane groups that hold ``rig``, from the outermost to the innermost."""
    if rig is None or scene is None or not _any_groups():
        return []
    parent_map = parent_map if parent_map is not None else _parent_map(scene)
    chain = []
    current = _layer_collection(rig)
    root = getattr(scene, "collection", None)
    visited = set()
    while current is not None and current != root:
        try:
            key = int(current.as_pointer())
        except FBP_DATA_ERRORS:
            break
        if key in visited or key not in parent_map:
            # Not linked in this scene's tree.
            break
        visited.add(key)
        if is_plane_group(current):
            chain.append(current)
        current = parent_map.get(key)
    chain.reverse()
    return chain


def group_rigs(collection, scene=None):
    """Frame By Plane layers (rigs with an image plane) inside ``collection``."""
    rigs = []
    if collection is None:
        return rigs
    scene_objects = getattr(scene, "objects", None) if scene is not None else None
    try:
        objects = tuple(collection.all_objects)
    except FBP_DATA_ERRORS:
        return rigs
    for obj in objects:
        try:
            if not bool(getattr(obj, "is_fbp_control", False)):
                continue
            if getattr(obj, "fbp_plane_target", None) is None:
                continue
            if scene_objects is not None and scene_objects.get(obj.name) != obj:
                continue
        except FBP_DATA_ERRORS:
            continue
        rigs.append(obj)
    return rigs


def entered_group(scene):
    """The group the artist entered with a double click, or ``None``."""
    name = _ENTERED.get(_scene_key(scene), "")
    if not name:
        return None
    collection = bpy.data.collections.get(name)
    if collection is None or not is_plane_group(collection):
        return None
    if int(collection.as_pointer()) not in _parent_map(scene):
        return None
    return collection


def selection_group(rig, scene, parent_map=None):
    """The group a plain click on ``rig`` selects, or ``None`` for the rig alone.

    Outside any entered group it is the outermost group of the rig. Inside
    an entered group it is the next group down, so nested groups open one
    level at a time; a rig directly in the entered group is picked alone.
    """
    chain = group_chain(rig, scene, parent_map)
    if not chain:
        return None
    entered = entered_group(scene)
    if entered is not None and entered in chain:
        index = chain.index(entered)
        return chain[index + 1] if index + 1 < len(chain) else None
    return chain[0]


def rig_outside_entered_group(rig, scene) -> bool:
    entered = entered_group(scene)
    if entered is None or rig is None:
        return False
    return entered not in group_chain(rig, scene)


def rig_in_closed_group(rig, scene) -> bool:
    """True when a click on ``rig`` selects a group rather than the rig."""
    if scene is None:
        return False
    if rig_outside_entered_group(rig, scene):
        return bool(group_chain(rig, scene))
    return selection_group(rig, scene) is not None


def select_group(context, collection, active_rig=None, *, toggle=False):
    """Select every layer of ``collection``; ``active_rig`` becomes active."""
    scene = getattr(context, "scene", None)
    view_layer = getattr(context, "view_layer", None)
    rigs = group_rigs(collection, scene)
    if not rigs or view_layer is None:
        return False
    selectable = []
    for rig in rigs:
        try:
            if bool(getattr(rig, "hide_select", False)) or not rig.visible_get():
                continue
        except FBP_DATA_ERRORS:
            continue
        selectable.append(rig)
    if not selectable:
        return False
    if active_rig not in selectable:
        active_rig = selectable[0]
    if toggle and all(rig.select_get() for rig in selectable):
        for rig in selectable:
            rig.select_set(False)
        return True
    if not toggle:
        keep = set(selectable)
        for obj in tuple(getattr(context, "selected_objects", ()) or ()):
            if obj not in keep:
                try:
                    obj.select_set(False)
                except FBP_DATA_ERRORS:
                    pass
    for rig in selectable:
        try:
            rig.select_set(True)
        except FBP_DATA_ERRORS:
            pass
    plane = getattr(active_rig, "fbp_plane_target", None)
    try:
        if plane is not None and plane.name not in view_layer.objects:
            plane = None
    except FBP_DATA_ERRORS:
        plane = None
    try:
        view_layer.objects.active = plane or active_rig
    except FBP_DATA_ERRORS:
        pass
    return True


def whole_group_selected_rigs(context):
    """Selected rigs whose whole (closed) group is selected.

    They show the group's box instead of one transform box each.
    """
    scene = getattr(context, "scene", None)
    if scene is None or not _any_groups():
        return set()
    parent_map = _parent_map(scene)
    result = set()
    checked = {}
    for obj in tuple(getattr(context, "selected_objects", ()) or ()):
        if not bool(getattr(obj, "is_fbp_control", False)):
            continue
        group = selection_group(obj, scene, parent_map)
        if group is None:
            continue
        key = group.name
        if key not in checked:
            checked[key] = all(rig.select_get() for rig in group_rigs(group, scene))
        if checked[key]:
            result.add(obj.name)
    return result


# -- Isolation (reduced opacity outside the entered group) ------------------

def _plane_materials(rig):
    plane = getattr(rig, "fbp_plane_target", None)
    try:
        return [mat for mat in plane.data.materials if mat is not None] if plane is not None else []
    except FBP_DATA_ERRORS:
        return []


def _dim_solid_color(rig, faded):
    """Solid shading: darken the viewport colour of the faded planes.

    Material Preview and Solid > Texture show the reduced opacity; Solid >
    Material shows every plane in its viewport colour, so the faded ones are
    also darkened there. The original colour is kept to restore it.
    """
    for mat in _plane_materials(rig):
        try:
            current = tuple(mat.diffuse_color)
            if faded:
                original = _SOLID_COLORS.setdefault(mat.name, current[:3])
                target = (*(value * ISOLATION_SOLID_DIM for value in original), current[3])
            else:
                original = _SOLID_COLORS.pop(mat.name, None)
                if original is None:
                    continue
                target = (*original, current[3])
            if any(abs(a - b) > 1.0e-6 for a, b in zip(current, target)):
                mat.diffuse_color = target
        except FBP_DATA_ERRORS:
            continue


def _fade_rig(rig, faded):
    try:
        from .materials import do_update_opacity
        base = max(0.0, min(1.0, float(getattr(rig, "fbp_opacity", 1.0))))
        if faded:
            do_update_opacity(rig, opacity=base * ISOLATION_FADE)
        else:
            do_update_opacity(rig)
        _dim_solid_color(rig, faded)
    except (ImportError, *FBP_DATA_ERRORS) as exc:
        try:
            from .runtime import fbp_warn
            fbp_warn("Could not change the group isolation opacity", exc)
        except ImportError:
            pass


def _scene_rigs(scene):
    rigs = []
    for obj in tuple(getattr(scene, "objects", ()) or ()):
        try:
            if bool(getattr(obj, "is_fbp_control", False)) and getattr(obj, "fbp_plane_target", None) is not None:
                rigs.append(obj)
        except FBP_DATA_ERRORS:
            continue
    return rigs


def apply_isolation(scene):
    """Fade every plane outside the entered group; restore the others."""
    key = _scene_key(scene)
    if not key:
        return
    entered = entered_group(scene)
    previously = set(_FADED.get(key, ()))
    wanted = set()
    if entered is not None and not _SUSPENDED["active"]:
        inside = {rig.name for rig in group_rigs(entered, scene)}
        wanted = {rig.name for rig in _scene_rigs(scene) if rig.name not in inside}
    for name in previously - wanted:
        rig = bpy.data.objects.get(name)
        if rig is not None:
            _fade_rig(rig, False)
    for name in wanted:
        rig = bpy.data.objects.get(name)
        if rig is not None:
            _fade_rig(rig, True)
    if wanted:
        _FADED[key] = wanted
    else:
        _FADED.pop(key, None)
    if entered is None:
        _ENTERED.pop(key, None)
    _tag_viewports()


def enter_group(scene, collection):
    key = _scene_key(scene)
    if not key or collection is None:
        return
    _ENTERED[key] = collection.name
    apply_isolation(scene)


def exit_group(scene, *, to_parent=False):
    """Leave the entered group (or go up to its parent group)."""
    key = _scene_key(scene)
    entered = entered_group(scene)
    target = None
    if to_parent and entered is not None:
        parent = _parent_map(scene).get(int(entered.as_pointer()))
        while parent is not None and not is_plane_group(parent):
            parent = _parent_map(scene).get(int(parent.as_pointer()))
        target = parent
    if target is not None:
        _ENTERED[key] = target.name
    else:
        _ENTERED.pop(key, None)
    apply_isolation(scene)


def _all_scenes():
    return tuple(getattr(bpy.data, "scenes", ()) or ())


def _restore_everything():
    for scene in _all_scenes():
        key = _scene_key(scene)
        for name in tuple(_FADED.get(key, ())):
            rig = bpy.data.objects.get(name)
            if rig is not None:
                _fade_rig(rig, False)
        _FADED.pop(key, None)


def _reapply_everything():
    for scene in _all_scenes():
        if _ENTERED.get(_scene_key(scene)):
            apply_isolation(scene)
    return None


def _schedule_reapply():
    try:
        if not bpy.app.timers.is_registered(_reapply_everything):
            bpy.app.timers.register(_reapply_everything, first_interval=0.0)
    except FBP_DATA_ERRORS:
        pass


@bpy.app.handlers.persistent
def fbp_plane_group_suspend(*_args):
    """Before Save or a render: the file and the image keep full opacity."""
    if not _FADED:
        return
    _SUSPENDED["active"] = True
    _restore_everything()


@bpy.app.handlers.persistent
def fbp_plane_group_resume(*_args):
    if not _SUSPENDED["active"]:
        return
    _SUSPENDED["active"] = False
    _schedule_reapply()


@bpy.app.handlers.persistent
def fbp_plane_group_load_pre(*_args):
    _ENTERED.clear()
    _FADED.clear()
    _SOLID_COLORS.clear()
    _SUSPENDED["active"] = False


@bpy.app.handlers.persistent
def fbp_plane_group_undo_redo(*_args):
    """Undo restores the saved materials: fade them again while inside."""
    if not _ENTERED:
        return
    for scene in _all_scenes():
        key = _scene_key(scene)
        if key in _FADED:
            # The restored data no longer carries the fade.
            _FADED[key] = set()
    _schedule_reapply()


_HANDLERS = (
    ("save_pre", fbp_plane_group_suspend),
    ("save_post", fbp_plane_group_resume),
    ("render_init", fbp_plane_group_suspend),
    ("render_complete", fbp_plane_group_resume),
    ("render_cancel", fbp_plane_group_resume),
    ("load_pre", fbp_plane_group_load_pre),
    ("undo_post", fbp_plane_group_undo_redo),
    ("redo_post", fbp_plane_group_undo_redo),
)


# -- Box rig ------------------------------------------------------------------

def _rect_corners(rig, depsgraph):
    try:
        from .layer_cage import layer_cage_rect
        rect = layer_cage_rect(rig, depsgraph)
    except (ImportError, *FBP_DATA_ERRORS):
        return None
    if rect is None:
        return None
    center, size = rect
    world = rig.matrix_world
    return [
        world @ Vector((center.x + dx * size.x * 0.5, center.y + dy * size.y * 0.5, center.z))
        for dx, dy in ((-1, -1), (1, -1), (1, 1), (-1, 1))
    ]


def group_box(collection, context, depsgraph=None, depth_cache=None):
    """``(front corners, back corners)`` of the group's box, or ``None``."""
    scene = getattr(context, "scene", None)
    rigs = []
    for rig in group_rigs(collection, scene):
        try:
            plane = rig.fbp_plane_target
            if plane is None or not plane.visible_get():
                continue
        except FBP_DATA_ERRORS:
            continue
        rigs.append(rig)
    if len(rigs) < 2:
        return None
    try:
        from .layers import fbp_layer_depth_value_from_cache, fbp_make_depth_context_cache
        depth_cache = depth_cache if depth_cache is not None else fbp_make_depth_context_cache(context)
        depths = [(fbp_layer_depth_value_from_cache(rig, depth_cache), index, rig) for index, rig in enumerate(rigs)]
    except (ImportError, *FBP_DATA_ERRORS):
        return None
    depths.sort(key=lambda item: (item[0], item[1]))
    front = _rect_corners(depths[0][2], depsgraph)
    back = _rect_corners(depths[-1][2], depsgraph)
    if front is None or back is None:
        return None
    return front, back


def box_segments(front, back):
    segments = []
    for corners in (front, back):
        for index in range(4):
            segments.extend((corners[index], corners[(index + 1) % 4]))
    for index in range(4):
        segments.extend((front[index], back[index]))
    return segments


def _scene_groups(scene):
    groups = []
    if not _any_groups():
        return groups
    root = getattr(scene, "collection", None)
    if root is None:
        return groups
    try:
        candidates = tuple(root.children_recursive)
    except FBP_DATA_ERRORS:
        return groups
    for collection in candidates:
        if is_plane_group(collection):
            groups.append(collection)
    return groups


def _collection_hidden(context, collection):
    """True when the collection is excluded or hidden in the View Layer."""
    view_layer = getattr(context, "view_layer", None)
    if view_layer is None:
        return False
    stack = [view_layer.layer_collection]
    while stack:
        layer = stack.pop()
        try:
            if layer.collection == collection:
                return bool(layer.exclude or layer.hide_viewport or collection.hide_viewport)
            stack.extend(layer.children)
        except FBP_DATA_ERRORS:
            continue
    return True


def visible_group_boxes(context, depsgraph=None):
    """``[(collection, segments)]`` for every shown plane group."""
    scene = getattr(context, "scene", None)
    if scene is None:
        return []
    groups = _scene_groups(scene)
    if not groups:
        return []
    try:
        from .layers import fbp_make_depth_context_cache
        depth_cache = fbp_make_depth_context_cache(context)
    except ImportError:
        depth_cache = None
    result = []
    for collection in groups:
        if _collection_hidden(context, collection):
            continue
        box = group_box(collection, context, depsgraph, depth_cache)
        if box is None:
            continue
        result.append((collection, box_segments(*box)))
    return result


def group_box_under_cursor(context, coord, radius):
    """The plane group whose box passes within ``radius`` pixels of ``coord``."""
    from bpy_extras.view3d_utils import location_3d_to_region_2d

    region = getattr(context, "region", None)
    region_data = getattr(context, "region_data", None)
    if region is None or region_data is None:
        return None
    try:
        depsgraph = context.evaluated_depsgraph_get()
    except FBP_DATA_ERRORS:
        depsgraph = None
    point = Vector((float(coord[0]), float(coord[1])))
    best = None
    for collection, segments in visible_group_boxes(context, depsgraph):
        for index in range(0, len(segments), 2):
            a = location_3d_to_region_2d(region, region_data, segments[index])
            b = location_3d_to_region_2d(region, region_data, segments[index + 1])
            if a is None or b is None:
                continue
            edge = b - a
            length = edge.length_squared
            t = 0.0 if length < 1.0e-9 else max(0.0, min(1.0, (point - a).dot(edge) / length))
            distance = (a + edge * t - point).length
            if distance <= radius and (best is None or distance < best[0]):
                best = (distance, collection)
    return None if best is None else best[1]


def _group_color(context, collection):
    tag = str(getattr(collection, "color_tag", "NONE") or "NONE")
    if tag.startswith("COLOR_"):
        try:
            index = int(tag.split("_")[-1]) - 1
            theme = context.preferences.themes[0]
            return tuple(theme.collection_color[index].color)[:3]
        except (ValueError, IndexError, *FBP_DATA_ERRORS):
            pass
    return _DEFAULT_GROUP_COLOR


def _tag_viewports():
    window_manager = getattr(bpy.context, "window_manager", None)
    for window in getattr(window_manager, "windows", ()) or ():
        screen = getattr(window, "screen", None)
        for area in getattr(screen, "areas", ()) or ():
            if area.type == "VIEW_3D":
                area.tag_redraw()


def _draw_group_boxes():
    global _LINE_SHADER
    import gpu
    from gpu_extras.batch import batch_for_shader

    context = bpy.context
    space = getattr(context, "space_data", None)
    region = getattr(context, "region", None)
    if space is None or region is None:
        return
    try:
        if not bool(space.overlay.show_overlays):
            return
    except FBP_DATA_ERRORS:
        return
    scene = getattr(context, "scene", None)
    if scene is None or not _scene_groups(scene):
        return
    try:
        depsgraph = context.evaluated_depsgraph_get()
    except FBP_DATA_ERRORS:
        depsgraph = None
    boxes = visible_group_boxes(context, depsgraph)
    if not boxes:
        return
    try:
        from .common import ui_scale
        scale = ui_scale(context)
    except ImportError:
        scale = 1.0
    if _LINE_SHADER is None:
        _LINE_SHADER = gpu.shader.from_builtin("POLYLINE_UNIFORM_COLOR")
    shader = _LINE_SHADER
    entered = entered_group(scene)
    entered_rigs = set(group_rigs(entered, scene)) if entered is not None else set()
    draws = []
    for collection, segments in boxes:
        rigs = group_rigs(collection, scene)
        selected = bool(rigs) and all(rig.select_get() for rig in rigs)
        partly = any(rig.select_get() for rig in rigs)
        color = _group_color(context, collection)
        if collection == entered:
            alpha, width = 1.0, _GROUP_SELECTED_WIDTH
        elif selected:
            alpha, width = 1.0, _GROUP_SELECTED_WIDTH
        elif partly:
            alpha, width = 0.85, _GROUP_LINE_WIDTH
        else:
            alpha, width = 0.6, _GROUP_LINE_WIDTH
        if entered is not None and collection != entered and not (set(rigs) <= entered_rigs):
            # Outside the entered group: faded like its planes.
            alpha *= 0.35
        draws.append((segments, (*color, alpha), width))
    gpu.state.blend_set("ALPHA")
    gpu.state.depth_test_set("NONE")
    gpu.state.depth_mask_set(False)
    try:
        shader.bind()
        shader.uniform_float("viewportSize", (region.width, region.height))
        for segments, color, width in draws:
            batch = batch_for_shader(shader, "LINES", {"pos": segments})
            shader.uniform_float("lineWidth", (width + _GROUP_HALO_EXTRA) * scale)
            shader.uniform_float("color", (0.0, 0.0, 0.0, 0.35 * color[3]))
            batch.draw(shader)
            shader.uniform_float("lineWidth", width * scale)
            shader.uniform_float("color", color)
            batch.draw(shader)
    finally:
        gpu.state.depth_mask_set(True)
        gpu.state.depth_test_set("LESS_EQUAL")
        gpu.state.blend_set("NONE")


def _cube_icon(x, y, size, color):
    """A small box drawn like the group rig: two squares joined at the corners."""
    import gpu
    from gpu_extras.batch import batch_for_shader
    from .common import uniform_color_shader

    side = size * 0.72
    off = size - side
    front = ((x, y), (x + side, y), (x + side, y + side), (x, y + side))
    back = tuple((px + off, py + off) for px, py in front)
    segments = []
    for square in (front, back):
        for index in range(4):
            segments.extend((square[index], square[(index + 1) % 4]))
    for index in range(4):
        segments.extend((front[index], back[index]))
    shader = uniform_color_shader()
    batch = batch_for_shader(shader, "LINES", {"pos": segments})
    shader.bind()
    shader.uniform_float("color", color)
    gpu.state.line_width_set(1.0)
    batch.draw(shader)


