    global FBP_DEPSGRAPH_HANDLER_ACTIVE
    global _FBP_SHARED_DEPSGRAPH_OBSERVERS, _FBP_NATIVE_OPS_APIS
    FBP_NATIVE_OPS_SYNC_RUNNING = False
    _FBP_SHARED_DEPSGRAPH_OBSERVERS = None
    _FBP_NATIVE_OPS_APIS = None
