def _fbp_is_guarded_layer_plane(obj):
    """Return True for native Frame By Plane mesh planes with mode filtering.

    Grease Pencil canvases and helper objects keep their own mode workflow. The
    guard targets only the actual FBP Mesh plane/card object selected in the
    viewport.
    """
    if obj is None:
        return False
    try:
        if not bool(getattr(obj, "is_fbp_plane", False)):
            return False
        if str(getattr(obj, "type", "") or "").upper() != "MESH":
            return False
        # Do not interfere with GP canvases or vector cutters if future versions
        # represent them with mesh helpers.
        if bool(obj.get("fbp_is_gp_canvas", False)) or bool(obj.get("fbp_is_gp_vector_cutter", False)):
            return False
        return True
    except FBP_DATA_ERRORS:
        return False


def _fbp_active_layer_plane_mode(context=None):
    context = context or getattr(bpy, "context", None)
    try:
        obj = getattr(context, "active_object", None)
    except FBP_DATA_ERRORS:
        return None, ""
    if not _fbp_is_guarded_layer_plane(obj):
        return None, ""
    try:
        return obj, str(getattr(obj, "mode", "OBJECT") or "OBJECT").upper()
    except FBP_DATA_ERRORS:
        return obj, "OBJECT"


def _fbp_restore_layer_plane_object_mode():
    """Timer callback: leave unsupported native modes on FBP layer planes."""
    context = getattr(bpy, "context", None)
    obj, mode = _fbp_active_layer_plane_mode(context)
    if obj is None or mode in FBP_PLANE_ALLOWED_OBJECT_MODES:
        return None
    try:
        if not bpy.ops.object.mode_set.poll():
            return 0.10
        bpy.ops.object.mode_set(mode="OBJECT")
        key = fbp_obj_runtime_key(obj) or str(getattr(obj, "name", "") or "")
        now = time.monotonic()
        previous = float(_FBP_PLANE_MODE_GUARD_LAST.get(key, 0.0) or 0.0)
        if now - previous > 2.0:
            _FBP_PLANE_MODE_GUARD_LAST[key] = now
            if len(_FBP_PLANE_MODE_GUARD_LAST) > 256:
                stale_keys = sorted(
                    _FBP_PLANE_MODE_GUARD_LAST,
                    key=_FBP_PLANE_MODE_GUARD_LAST.get,
                )[:64]
                for stale_key in stale_keys:
                    _FBP_PLANE_MODE_GUARD_LAST.pop(stale_key, None)
            fbp_warn(
                "Frame By Plane plane modes are limited to Object/Edit; "
                f"left unsupported mode {mode!r}."
            )
    except FBP_DATA_ERRORS:
        return None
    except Exception as exc:
        fbp_warn("Could not restore Object Mode for Frame By Plane plane", exc)
    return None


def _fbp_schedule_layer_plane_mode_guard(context=None):
    obj, mode = _fbp_active_layer_plane_mode(context)
    if obj is None or mode in FBP_PLANE_ALLOWED_OBJECT_MODES:
        return False
    return bool(
        fbp_safe_tasks.schedule_once(
            "fbp_layer_plane_mode_guard",
            _fbp_restore_layer_plane_object_mode,
            first_interval=FBP_PLANE_MODE_GUARD_DELAY,
        )
    )


