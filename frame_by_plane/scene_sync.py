def _fbp_dispatch_shared_depsgraph_observers(scene, depsgraph, updates, update_mask):
    """Run only observers relevant to one materialized depsgraph snapshot.

    Blender can emit a post-update callback with an empty update collection while
    finalizing a mode transition. Only the Grease Pencil observer uses that pulse
    to flush a structural edit; all other observers would immediately return.
    Skipping those calls also prevents the native-operations path from treating an
    empty callback as a reason to scan the active Scene.
    """
    try:
        observers = _fbp_shared_depsgraph_observers()
    except (ImportError, AttributeError, ReferenceError, RuntimeError, TypeError, ValueError) as exc:
        fbp_warn_once(
            "scene_sync.depsgraph_observers.resolve",
            "Shared depsgraph observers could not be resolved",
            exc,
        )
        return
    empty_updates = not updates
    for label, warning_key, callback, relevance_mask, run_on_empty in observers:
        if empty_updates and not run_on_empty:
            continue
        if not empty_updates and relevance_mask != _FBP_DG_ANY and not (update_mask & relevance_mask):
            continue
        try:
            callback(scene, depsgraph, updates=updates)
        except Exception as exc:
            fbp_warn_once(
                warning_key,
                f"{label} depsgraph observer skipped",
                exc,
            )

@bpy.app.handlers.persistent
def fbp_depsgraph_native_ops_handler(scene, depsgraph):
    """Observe native X/Delete and Shift+D, then defer every mutation.

    Blender 5.2 must not create, link or remove ID datablocks while the
    depsgraph is evaluating. This handler therefore only inspects state and
    schedules fbp_deferred_orphan_cleanup_timer(). Object removal, mesh/image/
    material removal and duplicate-plane repair all run from the timer.
    """
    if fbp_registration_busy():
        return
    fbp_note_depsgraph_activity()
    # The autonomous regression transaction replaces complete temporary Scene
    # graphs. Do not even inspect depsgraph RNA while those IDs are being freed.
    if bool(fbp_runtime_get("fbp_pause_managed_timers", False)):
        return
    try:
        resume_after = float(
            fbp_runtime_get("fbp_managed_timers_resume_after", 0.0) or 0.0
        )
    except (TypeError, ValueError):
        resume_after = 0.0
    if resume_after > time.monotonic():
        return
    if fbp_undo_guard_active() or fbp_render_mutation_blocked():
        return
    try:
        updates = tuple(getattr(depsgraph, "updates", ()) or ())
    except FBP_DATA_ERRORS:
        updates = ()
    update_mask = _fbp_depsgraph_update_type_mask(updates) if updates else 0
    _fbp_dispatch_shared_depsgraph_observers(scene, depsgraph, updates, update_mask)
    # Empty callbacks are useful only for the GP structural-edit flush above.
    # No ID changed, so native delete/duplicate repair has nothing to inspect.
    if not updates:
        return
    # Render depsgraph updates are not native edit operations. Inspecting every
    # evaluated frame wastes time and can queue repairs while render workers are
    # reading image/material data. The render-session guard owns this period.
    if bool(fbp_runtime_get("fbp_render_guard_active", False)) or fbp_render_job_active():
        return
    if fbp_undo_is_active():
        return
    # Materials, images and node trees cannot represent native layer deletion,
    # duplication or collection unlinking. Their observers have already run.
    if updates and not (update_mask & _FBP_DG_NATIVE_OPS):
        return

    global FBP_DEPSGRAPH_HANDLER_ACTIVE

    if FBP_NATIVE_OPS_SYNC_RUNNING:
        return

    context = bpy.context
    if not context or not scene or getattr(context, "scene", None) != scene:
        return

    # Cheap selected-plane mode filter. Scheduling only; the actual mode change
    # runs from a timer outside depsgraph evaluation.
    _fbp_schedule_layer_plane_mode_guard(context)

    FBP_DEPSGRAPH_HANDLER_ACTIVE = True
    try:
        auto_clean = bool(getattr(scene, 'fbp_auto_clean_orphans', False))
        (
            candidate_rigs,
            has_orphan_plane,
            relation_collections,
            updated_meshes,
        ) = _fbp_depsgraph_fbp_hints(
            depsgraph, scene, check_orphans=auto_clean, updates=updates
        )
        try:
            (
                schedule_object_mask_geometry_updates,
                fbp_depsgraph_schedule_drawing_updates,
                fbp_schedule_clipping_mask_sync,
                fbp_schedule_object_mask_binding_sync,
            ) = _fbp_native_ops_apis()
        except (ImportError, AttributeError, ReferenceError, RuntimeError, TypeError, ValueError) as exc:
            fbp_warn_once(
                "scene_sync.native_ops_apis",
                "Native operation observer services could not be resolved",
                exc,
            )
            schedule_object_mask_geometry_updates = None
            fbp_depsgraph_schedule_drawing_updates = None
            fbp_schedule_clipping_mask_sync = None
            fbp_schedule_object_mask_binding_sync = None
        if schedule_object_mask_geometry_updates is not None:
            schedule_object_mask_geometry_updates(
                scene, updated_meshes=updated_meshes
            )
        if fbp_depsgraph_schedule_drawing_updates is not None:
            fbp_depsgraph_schedule_drawing_updates(scene, candidate_rigs)
        # Relation sources refresh only after explicit layer/collection changes.
        # Camera animation is consumed natively and no longer enters this Python
        # hot path.
        if relation_collections and fbp_schedule_clipping_mask_sync is not None:
            fbp_schedule_clipping_mask_sync(
                scene, collections=relation_collections
            )
        topology_changed = _fbp_scene_object_count_changed(scene, update=True)
        if topology_changed:
            if fbp_schedule_clipping_mask_sync is not None:
                fbp_schedule_clipping_mask_sync(scene)
            if fbp_schedule_object_mask_binding_sync is not None:
                fbp_schedule_object_mask_binding_sync(scene)
        # Object totals catch ordinary X/Delete immediately. A throttled known-link
        # probe also catches replace/unlink operations where one object disappears
        # while another is added in the same depsgraph update and the total stays
        # unchanged. Skip the fallback probe during playback to keep frame updates
        # lightweight; the slow safety timer remains available afterward.
        probe_deleted_links = topology_changed or (
            _fbp_deleted_link_probe_due(scene)
            and not fbp_animation_playback_active(context)
        )
        has_deleted_rig = bool(
            probe_deleted_links
            and _fbp_get_known_links(scene)
            and fbp_known_links_have_deleted_rig(scene)
        )
        has_broken_duplicate = fbp_scene_has_broken_native_duplicate(
            scene, candidates=candidate_rigs
        )

        if not has_deleted_rig and not has_orphan_plane and not has_broken_duplicate:
            return

        # Definitive safety rule:
        # whether this is X/Delete cleanup or Shift+D duplicate repair, do not
        # touch Blender ID memory from depsgraph_update_post. The timer will run
        # immediately after Blender returns to an idle/safe state.
        fbp_schedule_deferred_orphan_cleanup("depsgraph native ops repair", first_interval=0.03)

    except Exception as exc:
        fbp_warn("Depsgraph native operation handler skipped", exc)
    finally:
        FBP_DEPSGRAPH_HANDLER_ACTIVE = False

def fbp_scene_has_orphan_fbp_plane_light(scene=None, *, candidates=None):
    """Cheap safety-net check used by the slow cleanup timer.

    The timer should not rebuild the whole Layer UI every few seconds. It first
    checks whether at least one FBP plane actually looks orphaned; only then it
    runs the heavier cleanup/sync path.
    """
    scene = scene or getattr(bpy.context, "scene", None)
    if not scene:
        return False
    if candidates is None:
        candidates = fbp_scene_fallback_candidates(scene)
    link_identities = _fbp_get_known_link_identities(scene)
    try:
        for obj in list(candidates or ()):
            if not getattr(obj, "is_fbp_plane", False):
                continue
            parent = getattr(obj, "parent", None)
            if parent and getattr(parent, "is_fbp_control", False) and object_in_scene(parent, scene):
                continue
            rig_name = ""
            try:
                rig_name = obj.get("fbp_parent_rig_name", "")
            except Exception:
                rig_name = ""
            if rig_name and _fbp_resolve_snapshot_rig(
                scene, rig_name, link_identities
            ) is not None:
                continue
            return True
    except Exception as exc:
        fbp_warn("Could not inspect possible orphan FBP planes", exc)
    return False


def cleanup_orphan_fbp_planes_timer():
    """Low-frequency safety net for changes missed by depsgraph notifications."""
    interval = FBP_FALLBACK_TIMER_INTERVAL

    context = bpy.context
    # This callback runs from Blender's idle timer and is therefore a safe backup
    # if the dedicated persistent watchdog was lost during a reload.
    fbp_undo_is_active(release_expired=True)
    if fbp_background_sync_should_pause(context):
        return interval
    scene = getattr(context, "scene", None) if context else None
    if not context or not scene:
        return interval

    changed = 0
    try:
        now = time.monotonic()
        _clock_key, scan_clock = _fbp_fallback_scan_clock(scene, now)
        known_links = _fbp_get_known_links(scene)
        has_deleted_rig = bool(known_links) and fbp_known_links_have_deleted_rig(scene)
        duplicate_scan_due = (
            now - float(scan_clock.get("duplicate", 0.0) or 0.0)
            >= FBP_FALLBACK_DUPLICATE_SCAN_INTERVAL
        )
        auto_clean = bool(getattr(scene, 'fbp_auto_clean_orphans', False))
        orphan_scan_due = (
            auto_clean
            and now - float(scan_clock.get("orphan", 0.0) or 0.0)
            >= FBP_FALLBACK_ORPHAN_SCAN_INTERVAL
        )
        if not has_deleted_rig and not duplicate_scan_due and not orphan_scan_due:
            return interval

        # Build the cached/tagged candidate set only when a safety scan is due.
        # The common 10-second timer pulse otherwise performs no collection walk.
        candidates = (
            fbp_scene_fallback_candidates(scene)
            if duplicate_scan_due or orphan_scan_due
            else []
        )
        # Record completed empty scans as well; otherwise an empty project would
        # repeat the collection-cache walk on every 10-second timer pulse.
        if duplicate_scan_due:
            scan_clock["duplicate"] = now
        if orphan_scan_due:
            scan_clock["orphan"] = now
        if not candidates and not known_links:
            return interval

        # Shift+D is normally caught from touched depsgraph objects. Keep a
        # much slower cached/tagged-object scan only as a safety net.
        has_broken_duplicate = False
        if duplicate_scan_due:
            has_broken_duplicate = fbp_scene_has_broken_native_duplicate(
                scene, candidates=candidates
            )

        if has_deleted_rig or has_broken_duplicate:
            changed += int(
                fbp_run_native_ops_sync(
                    context,
                    scene,
                    force=False,
                    delete_hint=has_deleted_rig,
                    duplicate_hint=has_broken_duplicate,
                    refresh_layers=False,
                ) or 0
            )

        if orphan_scan_due:
            if fbp_scene_has_orphan_fbp_plane_light(scene, candidates=candidates):
                changed += int(cleanup_orphan_fbp_planes(context, force=False) or 0)

        if changed:
            sync_layer_collection(context)
    except Exception as exc:
        fbp_warn("Slow orphan cleanup timer skipped", exc)
    return interval
