# One compact type mask is computed per depsgraph callback. It lets the shared
# dispatcher skip observers whose inputs cannot have changed instead of making
# each observer traverse the same material/image-only update batch.
_FBP_DG_OBJECT = 1 << 0
_FBP_DG_MESH = 1 << 1
_FBP_DG_LATTICE = 1 << 2
_FBP_DG_CAMERA = 1 << 3
_FBP_DG_SCENE = 1 << 4
_FBP_DG_COLLECTION = 1 << 5
_FBP_DG_NODETREE = 1 << 6
_FBP_DG_MATERIAL = 1 << 7
_FBP_DG_GREASE_PENCIL = 1 << 8
_FBP_DG_OTHER = 1 << 9
_FBP_DG_ANY = (1 << 10) - 1
_FBP_DG_NATIVE_OPS = _FBP_DG_OBJECT | _FBP_DG_MESH | _FBP_DG_SCENE | _FBP_DG_COLLECTION
_FBP_DG_GREASE_PENCIL_OBSERVER = (
    _FBP_DG_OBJECT
    | _FBP_DG_MESH
    | _FBP_DG_CAMERA
    | _FBP_DG_SCENE
    | _FBP_DG_MATERIAL
    | _FBP_DG_GREASE_PENCIL
)


def _fbp_depsgraph_update_type_mask(updates):
    """Classify one materialized update tuple without retaining RNA wrappers."""
    mask = 0
    object_rna = bpy.types.Object
    mesh_rna = bpy.types.Mesh
    lattice_rna = bpy.types.Lattice
    camera_rna = bpy.types.Camera
    scene_rna = bpy.types.Scene
    collection_rna = bpy.types.Collection
    node_tree_rna = bpy.types.NodeTree
    material_rna = bpy.types.Material
    grease_pencil_rna = getattr(bpy.types, "GreasePencil", None)
    for update in updates:
        try:
            datablock = getattr(update, "id", None)
            original = getattr(datablock, "original", None)
            if original is not None:
                datablock = original
            if isinstance(datablock, object_rna):
                mask |= _FBP_DG_OBJECT
            elif isinstance(datablock, mesh_rna):
                mask |= _FBP_DG_MESH
            elif isinstance(datablock, lattice_rna):
                mask |= _FBP_DG_LATTICE
            elif isinstance(datablock, camera_rna):
                mask |= _FBP_DG_CAMERA
            elif isinstance(datablock, scene_rna):
                mask |= _FBP_DG_SCENE
            elif isinstance(datablock, collection_rna):
                mask |= _FBP_DG_COLLECTION
            elif isinstance(datablock, node_tree_rna):
                mask |= _FBP_DG_NODETREE
            elif isinstance(datablock, material_rna):
                mask |= _FBP_DG_MATERIAL
            elif (
                grease_pencil_rna is not None
                and isinstance(datablock, grease_pencil_rna)
            ) or type(datablock).__name__.upper() == "GREASEPENCIL":
                mask |= _FBP_DG_GREASE_PENCIL
            else:
                mask |= _FBP_DG_OTHER
        except FBP_DATA_ERRORS:
            mask |= _FBP_DG_OTHER
    return mask


def _fbp_scene_cache_key(scene):
    if scene is None:
        return None
    try:
        identity = fbp_obj_runtime_key(scene)
        if identity is None:
            return None
        return (
            identity,
            str(getattr(scene, "name_full", getattr(scene, "name", "")) or ""),
        )
    except FBP_DATA_ERRORS:
        return None


def _fbp_scene_object_count_changed(scene, *, update=True):
    key = _fbp_scene_cache_key(scene)
    if key is None:
        return True
    try:
        count = len(scene.objects)
    except FBP_DATA_ERRORS:
        return True
    previous = _FBP_SCENE_OBJECT_COUNT_CACHE.get(key)
    if update:
        if len(_FBP_SCENE_OBJECT_COUNT_CACHE) >= 64 and key not in _FBP_SCENE_OBJECT_COUNT_CACHE:
            _FBP_SCENE_OBJECT_COUNT_CACHE.clear()
        _FBP_SCENE_OBJECT_COUNT_CACHE[key] = count
    return previous is None or previous != count


