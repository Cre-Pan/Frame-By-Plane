def _fbp_build_plane_ownership_index(objects):
    """Index plane ownership once for batch delete/repair operations."""
    index = {
        "claimants": {},
        "parent_planes": {},
        "name_planes": {},
    }
    for candidate in list(objects or ()):
        try:
            candidate_key = _fbp_object_identity(candidate)
            if getattr(candidate, "is_fbp_control", False):
                target = getattr(candidate, "fbp_plane_target", None)
                plane_key = _fbp_object_identity(target)
                if candidate_key is not None and plane_key is not None:
                    index["claimants"].setdefault(plane_key, set()).add(
                        candidate_key
                    )
                continue
            if not getattr(candidate, "is_fbp_plane", False):
                continue

            parent = getattr(candidate, "parent", None)
            parent_key = _fbp_object_identity(parent)
            if parent_key is not None and getattr(parent, "is_fbp_control", False):
                index["parent_planes"].setdefault(parent_key, []).append(candidate)

            names = set()
            candidate_name = str(getattr(candidate, "name", "") or "")
            if candidate_name.startswith("Plane_") and len(candidate_name) > 6:
                names.add(candidate_name[6:])
            stored_name = str(candidate.get("fbp_parent_rig_name", "") or "")
            if stored_name:
                names.add(stored_name)
            for name in names:
                index["name_planes"].setdefault(name, []).append(candidate)
        except FBP_DATA_IO_ERRORS:
            continue
    return index


def fbp_linked_planes_for_rig(
    rig, scene=None, *, objects=None, ownership_index=None
):
    """Find planes owned by ``rig`` without adopting another live rig's plane.

    ``objects`` and ``ownership_index`` let multi-rig deletion reuse one Scene
    scan instead of rebuilding ownership information for every layer.
    """
    planes = []
    seen = set()
    if not rig:
        return planes

    if ownership_index is None:
        if objects is None:
            try:
                objects = list(scene.objects if scene else bpy.data.objects)
            except FBP_DATA_ERRORS:
                objects = []
        elif not isinstance(objects, (list, tuple)):
            objects = list(objects or ())
        ownership_index = _fbp_build_plane_ownership_index(objects)
    target_claimants = ownership_index.get("claimants", {}) or {}
    parent_planes = ownership_index.get("parent_planes", {}) or {}
    name_planes = ownership_index.get("name_planes", {}) or {}

    rig_identity = _fbp_object_identity(rig)

    def is_claimed_by_other(obj):
        try:
            parent = getattr(obj, "parent", None)
            if (
                parent
                and _fbp_object_identity(parent) != rig_identity
                and getattr(parent, "is_fbp_control", False)
            ):
                if scene is None or object_in_scene(parent, scene):
                    return True
            plane_key = _fbp_object_identity(obj)
            claimants = target_claimants.get(plane_key, ()) if plane_key is not None else ()
            return any(owner_key != rig_identity for owner_key in claimants)
        except FBP_DATA_ERRORS:
            return True

    def add_plane(obj, *, fallback=False):
        try:
            key = _fbp_object_identity(obj)
            if (
                key is None
                or key in seen
                or not getattr(obj, "is_fbp_plane", False)
                or bpy.data.objects.get(obj.name) != obj
                or (fallback and is_claimed_by_other(obj))
            ):
                return
            seen.add(key)
            planes.append(obj)
        except FBP_DATA_ERRORS:
            return

    try:
        explicit_target = getattr(rig, "fbp_plane_target", None)
        if (
            explicit_target is not None
            and _fbp_object_identity(getattr(explicit_target, "parent", None)) == rig_identity
        ):
            add_plane(explicit_target)
        else:
            add_plane(explicit_target, fallback=True)
    except ReferenceError:
        pass

    rig_name = str(getattr(rig, "name", "") or "")
    for obj in list(parent_planes.get(rig_identity, ())):
        add_plane(obj)
    for obj in list(name_planes.get(rig_name, ())):
        add_plane(obj, fallback=True)
    return planes


def fbp_quarantine_orphan_plane(plane, *, rig_name=""):
    """Hide one orphan plane without deleting IDs outside an Undo operator."""
    if plane is None:
        return False
    try:
        already = bool(plane.get(FBP_ORPHAN_QUARANTINE_KEY, False))
        if not already:
            plane[FBP_ORPHAN_HIDE_RENDER_KEY] = bool(getattr(plane, "hide_render", False))
            plane[FBP_ORPHAN_HIDE_VIEWPORT_KEY] = bool(getattr(plane, "hide_viewport", False))
            try:
                plane[FBP_ORPHAN_HIDE_SET_KEY] = bool(plane.hide_get())
            except FBP_DATA_ERRORS:
                plane[FBP_ORPHAN_HIDE_SET_KEY] = False
        if rig_name:
            plane["fbp_parent_rig_name"] = str(rig_name)
        plane[FBP_ORPHAN_QUARANTINE_KEY] = True
        plane["fbp_orphan_candidate"] = True
        plane.hide_render = True
        plane.hide_viewport = True
        try:
            plane.hide_set(True)
        except FBP_DATA_ERRORS:
            pass
        return not already
    except FBP_DATA_IO_ERRORS:
        return False


def fbp_restore_quarantined_plane(plane, rig=None):
    """Restore a quarantined plane after Undo/Redo recreates its owner rig."""
    if plane is None:
        return False
    try:
        if not bool(plane.get(FBP_ORPHAN_QUARANTINE_KEY, False)):
            return False
        if rig is not None:
            if getattr(plane, "parent", None) is None:
                plane.parent = rig
            try:
                target = getattr(rig, "fbp_plane_target", None)
                if target is None or target is plane:
                    rig.fbp_plane_target = plane
            except FBP_DATA_ERRORS:
                pass
            plane["fbp_parent_rig_name"] = str(getattr(rig, "name", "") or "")
        plane.hide_render = bool(plane.get(FBP_ORPHAN_HIDE_RENDER_KEY, False))
        plane.hide_viewport = bool(plane.get(FBP_ORPHAN_HIDE_VIEWPORT_KEY, False))
        try:
            plane.hide_set(bool(plane.get(FBP_ORPHAN_HIDE_SET_KEY, False)))
        except FBP_DATA_ERRORS:
            pass
        for key in (
            FBP_ORPHAN_QUARANTINE_KEY,
            FBP_ORPHAN_HIDE_RENDER_KEY,
            FBP_ORPHAN_HIDE_VIEWPORT_KEY,
            FBP_ORPHAN_HIDE_SET_KEY,
            "fbp_orphan_candidate",
        ):
            try:
                if key in plane:
                    del plane[key]
            except FBP_DATA_IO_ERRORS:
                pass
        return True
    except FBP_DATA_IO_ERRORS:
        return False


def fbp_restore_quarantined_planes(scene=None):
    """Reconnect quarantined planes whose owner exists again after history restore."""
    scene = scene or getattr(getattr(bpy, "context", None), "scene", None)
    if scene is None:
        return 0
    restored = 0
    try:
        candidates = tuple(iter_scene_fbp_planes(scene, fallback=True))
    except (AttributeError, ReferenceError, RuntimeError, TypeError, ValueError):
        try:
            candidates = tuple(obj for obj in scene.objects if getattr(obj, "is_fbp_plane", False))
        except FBP_DATA_ERRORS:
            candidates = ()
    for plane in candidates:
        try:
            if not bool(plane.get(FBP_ORPHAN_QUARANTINE_KEY, False)):
                continue
            rig_name = str(plane.get("fbp_parent_rig_name", "") or "")
            rig = bpy.data.objects.get(rig_name) if rig_name else None
            if not (
                rig
                and getattr(rig, "is_fbp_control", False)
                and object_in_scene(rig, scene)
            ):
                continue
            restored += int(fbp_restore_quarantined_plane(plane, rig))
        except FBP_DATA_ERRORS:
            continue
    return restored


